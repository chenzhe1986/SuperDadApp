function buildConfig(z) {
  let coreZ = 0;
  for (const nz in NOBLE_CORE) {
    if (z > +nz && +nz > coreZ) coreZ = +nz;
  }
  let core = '';
  let remaining = z;
  if (coreZ > 0) {
    core = '[' + NOBLE_CORE[coreZ] + ']';
    remaining = z - coreZ;
  }
  let suffix = CONFIG_SUFFIX_OVERRIDES[z];
  if (!suffix) {
    const parts = [];
    for (let i = 0; i < AUFBAU.length && remaining > 0; i++) {
      const n = AUFBAU[i][0], l = AUFBAU[i][1], cap = AUFBAU[i][2];
      const take = Math.min(cap, remaining);
      parts.push(n + ORB_LETTER[l] + supNum(take));
      remaining -= take;
    }
    suffix = parts.join('');
  }
  return core + suffix;
}

