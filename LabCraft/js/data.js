// ---------- 周期表定位：返回 [行, 列]（主表 1~7 行 + 镧系第 9 行 + 锕系第 10 行） ----------
function tablePos(z) {
  if (z === 1) return [1, 1];
  if (z === 2) return [1, 18];
  if (z <= 4) return [2, z - 2];        // Li 第 1 列, Be 第 2 列
  if (z <= 10) return [2, z + 8];       // B~Ne → 第 13~18 列
  if (z <= 12) return [3, z - 10];
  if (z <= 18) return [3, z];
  if (z <= 36) return [4, z - 18];
  if (z <= 54) return [5, z - 36];
  if (z <= 56) return [6, z - 54];
  if (z <= 71) return [9, z - 54];      // 镧系 57~71 → 第 9 行第 3~17 列
  if (z <= 86) return [6, z - 68];      // Hf~Rn → 第 4~18 列
  if (z <= 88) return [7, z - 86];
  if (z <= 103) return [10, z - 86];    // 锕系 89~103 → 第 10 行第 3~17 列
  return [7, z - 100];                  // Rf~Og → 第 4~18 列
}

