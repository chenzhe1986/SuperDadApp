// ---------- 双原子单质生成 ----------
function diatomic(sym, half, order) {
  return {
    atoms: [{ element: sym, pos: [-half, 0, 0] }, { element: sym, pos: [half, 0, 0] }],
    bonds: [[0, 1, order || 1]],
  };
}
// ---------- M2O3 型氧化物簇（刚玉/稀土氧化物示意：两个 M 由 3 个氧桥连） ----------
function sesquiCluster(sym, mO) {
  const r = mO || 1.9;
  const mx = Math.sqrt(Math.max(r * r - 0.81, 0.01)); // 使 M-O 键长约等于 r
  const atoms = [
    { element: sym, pos: [-mx, 0, 0] },
    { element: sym, pos: [mx, 0, 0] },
    { element: 'O', pos: [0, 0, 0.9] },
    { element: 'O', pos: [0, -0.78, -0.45] },
    { element: 'O', pos: [0, 0.78, -0.45] },
  ];
  const bonds = [[0, 2], [0, 3], [0, 4], [1, 2], [1, 3], [1, 4]];
  return { atoms, bonds };
}
// ---------- MO2 型萤石结构单元簇（中心 M + 8 个立方角 X，X 默认为 O） ----------
function fluoriteCluster(sym, half, ligand) {
  const h = half || 1.05;
  const X = ligand || 'O';
  const atoms = [{ element: sym, pos: [0, 0, 0] }];
  const bonds = [];
  const dirs = [];
  [-h, h].forEach(function (x) { [-h, h].forEach(function (y) { [-h, h].forEach(function (z) { dirs.push([x, y, z]); }); }); });
  dirs.forEach(function (d, i) {
    atoms.push({ element: X, pos: d });
    bonds.push([0, i + 1]);
  });
  return { atoms, bonds };
}

