/* ---------------- 基础工具 ---------------- */
function ri(min, max) { return Math.floor(Math.random() * (max - min + 1)) + min }
function shuffle(a) {
  a = a.slice()
  for (let i = a.length - 1; i > 0; i--) { const j = ri(0, i);[a[i], a[j]] = [a[j], a[i]] }
  return a
}
function pick(arr) { return arr[ri(0, arr.length - 1)] }

// 组装题目：correct 为正确选项文本，distractors 为 3 个干扰项
function make(grade, subject, difficulty, question, correct, distractors, explanation) {
  const opts = shuffle([correct].concat(distractors))
  return {
    grade: grade, subject: subject, difficulty: difficulty,
    type: 'single', question: question, options: opts,
    answer: opts.indexOf(correct), explanation: explanation
  }
}

// 生成 3 个与 correct 及彼此不同的数值干扰项（非负），以字符串返回
function numD(correct, spread) {
  const set = new Set()
  let guard = 0
  while (set.size < 3 && guard < 300) {
    guard++
    const d = correct + (ri(0, 1) ? 1 : -1) * ri(1, spread)
    if (d === correct || d < 0) continue
    set.add(d)
  }
  let k = 1
  while (set.size < 3) { const c = correct + k; if (c !== correct && !set.has(c)) set.add(c); k++ }
  return Array.from(set).map(String)
}

// 从同池词语里挑 3 个不等于正确答案的干扰项
function textD(correct, pool) {
  const out = []
  for (const w of shuffle(pool)) {
    if (w !== correct && out.indexOf(w) === -1) out.push(w)
    if (out.length === 3) break
  }
  let k = 0
  while (out.length < 3) { out.push('　'.repeat(++k) + correct) } // 兜底，正常不会走到
  return out
}

