  const raw = fs.readFileSync(file, 'utf8')
  const existing = JSON.parse(raw)
  const seen = new Set(existing.map(q => q.question))
  let idNum = maxIdNum(existing)

  const added = []
  // 1) 人文社科 + 科学：抽尽知识池（库被抽尽就如实少补，不用数学填充）
  KNOWLEDGE.forEach(k => drainPool(k[0], grade, k[1], k[2], seen, added))
  const knowledgeCount = added.length

  // 2) 数学：只出巧算 + 常识，且不超过本次新增的 MATH_RATIO
  //    M / (M + K) ≤ r  →  M ≤ K·r/(1-r)
  const mathTarget = Math.floor(knowledgeCount * MATH_RATIO / (1 - MATH_RATIO))
  let mathAdded = 0, guard = 0
  while (mathAdded < mathTarget && guard < mathTarget * 60 + 300) {
    guard++
    const q = genMathTrick(grade)
    if (seen.has(q.question)) continue
    seen.add(q.question)
    added.push(q)
    mathAdded++
  }

  // 3) 续编 id 后写回（保留已有题目，仅追加）
  added.forEach(q => { idNum++; q.id = 'g' + grade + '-' + idNum })
  const all = existing.concat(added)
  fs.writeFileSync(file, '[\n' + all.map(q => JSON.stringify(q)).join(',\n') + '\n]\n', 'utf8')

  grand.existing += existing.length; grand.knowledge += knowledgeCount; grand.math += mathAdded
