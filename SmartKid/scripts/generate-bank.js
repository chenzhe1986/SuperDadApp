// 取现有题库中最大的 id 数字（g{grade}-{n} 中的 n）
function maxIdNum(list) {
  let m = 0
  for (const q of list) {
    const mt = /(\d+)\s*$/.exec(String(q.id))
    if (mt) { const n = parseInt(mt[1], 10); if (n > m) m = n }
  }
  return m
}

// 把知识池中尚未出现（按题干去重）的题目全部取出
function drainPool(pool, grade, subject, defaultDiff, seen, out) {
  let added = 0
  for (const it of pool) {
    const q = it[0]
    if (seen.has(q)) continue
    seen.add(q)
    out.push(build(null, grade, subject, it[4] || defaultDiff, it[0], it[1], it[2].slice(0, 3), it[3]))
    added++
  }
  return added
}

