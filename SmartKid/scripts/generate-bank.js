/* ---------------- 基础工具 ---------------- */
function ri(min, max) { return Math.floor(Math.random() * (max - min + 1)) + min }
function pick(arr) { return arr[ri(0, arr.length - 1)] }
function shuffle(a) {
  a = a.slice()
  for (let i = a.length - 1; i > 0; i--) { const j = ri(0, i);[a[i], a[j]] = [a[j], a[i]] }
  return a
}

// 组装题目：correct 为正确选项文本，distractors 为 3 个干扰项文本
function build(id, grade, subject, difficulty, question, correct, distractors, explanation) {
  const opts = shuffle([correct].concat(distractors))
  const answer = opts.indexOf(correct)
  return {
    id: id, grade: grade, subject: subject, difficulty: difficulty,
    type: 'single', question: question, options: opts, answer: answer,
    explanation: explanation
  }
}

// 生成 count 个与 correct 及彼此都不同的数值干扰项（非负）
function numDistractors(correct, count, spread) {
  const set = new Set()
  let guard = 0
  while (set.size < count && guard < 400) {
    guard++
    const sign = ri(0, 1) ? 1 : -1
    const d = correct + sign * ri(1, spread)
    if (d === correct || d < 0) continue
    set.add(d)
  }
  let k = 1
  while (set.size < count) { const cand = correct + k; if (cand !== correct && !set.has(cand)) set.add(cand); k++ }
  return Array.from(set).slice(0, count).map(String)
}

// 从知识条目池取一题：item = [题干, 正确答案, [3个干扰项], 解析, 难度?]
function makeFromPool(pool, grade, subject, defaultDiff) {
  const it = pick(pool)
  return build(null, grade, subject, it[4] || defaultDiff, it[0], it[1], it[2].slice(0, 3), it[3])
}

/* ---------------- 数学：巧算技巧题（答案由计算保证正确） ---------------- */
function genMathTrick(grade) {
  const kinds = ['sq5', 'sameTen', 'mul11', 'mul5', 'mul25', 'mul9', 'mul99', 'sense', 'sense', 'sense']
  const t = pick(kinds)
  if (t === 'sq5') {
    const a = ri(1, 9), n = 10 * a + 5, ans = 100 * a * (a + 1) + 25
    return build(null, grade, '数学', '中等', '巧算：' + n + '² = ?', String(ans),
      numDistractors(ans, 3, Math.max(20, Math.round(ans * 0.05))),
      '个位是 5 的两位数求平方：十位 ' + a + ' ×（十位+1）= ' + a + '×' + (a + 1) + ' = ' + (a * (a + 1)) + '，后面直接接 25，得 ' + ans + '。')
  }
  if (t === 'sameTen') {
    const a = ri(1, 9), b = ri(1, 9), c = 10 - b
    const x = 10 * a + b, y = 10 * a + c, ans = x * y
    const bc = b * c, bcStr = bc < 10 ? '0' + bc : '' + bc
    return build(null, grade, '数学', '中等', '巧算：' + x + ' × ' + y + ' = ?', String(ans),
      numDistractors(ans, 3, Math.max(20, Math.round(ans * 0.05))),
      '十位相同、个位相加为 10：十位 ' + a + '×（' + a + '+1）= ' + (a * (a + 1)) + ' 作前段，个位相乘 ' + b + '×' + c + ' = ' + bcStr + ' 作后两位，得 ' + ans + '。')
  }
  if (t === 'mul11') {
    const x = ri(12, 98), ans = x * 11
    return build(null, grade, '数学', '中等', '巧算：' + x + ' × 11 = ?', String(ans),
      numDistractors(ans, 3, Math.max(15, Math.round(ans * 0.08))),
      '两位数 × 11：' + x + ' × 11 = ' + x + '×10 + ' + x + ' = ' + ans + '（口诀“两边一拉、中间相加”）。')
  }
  if (t === 'mul5') {
    const x = ri(24, 198), ans = x * 5
    return build(null, grade, '数学', '简单', '巧算：' + x + ' × 5 = ?', String(ans),
      numDistractors(ans, 3, Math.max(15, Math.round(ans * 0.08))),
      '× 5 = × 10 ÷ 2：' + x + '×10 = ' + (x * 10) + '，再除以 2 得 ' + ans + '。')
  }
  if (t === 'mul25') {
    const x = ri(8, 96) * 4 / 4 // 保持整数
    const v = ri(8, 96), ans = v * 25
    return build(null, grade, '数学', '中等', '巧算：' + v + ' × 25 = ?', String(ans),
      numDistractors(ans, 3, Math.max(20, Math.round(ans * 0.06))),
      '× 25 = × 100 ÷ 4：' + v + '×100 = ' + (v * 100) + '，再除以 4 得 ' + ans + '。')
  }
  if (t === 'mul9') {
    const x = ri(12, 99), ans = x * 9
    return build(null, grade, '数学', '简单', '巧算：' + x + ' × 9 = ?', String(ans),
      numDistractors(ans, 3, Math.max(12, Math.round(ans * 0.08))),
      '× 9 = × 10 − 本身：' + x + '×10 = ' + (x * 10) + '，再减 ' + x + ' 得 ' + ans + '。')
  }
  if (t === 'mul99') {
    const x = ri(11, 99), ans = x * 99
    return build(null, grade, '数学', '中等', '巧算：' + x + ' × 99 = ?', String(ans),
      numDistractors(ans, 3, Math.max(20, Math.round(ans * 0.06))),
      '× 99 = × 100 − 本身：' + x + '×100 = ' + (x * 100) + '，再减 ' + x + ' 得 ' + ans + '。')
  }
  return makeFromPool(MATH_SENSE, grade, '数学', '简单')
}

